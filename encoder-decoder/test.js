/* Encoder-Decoder: tests in the real PortD 1.0.0, in headless Chrome, with real mouse, keyboard and touch input.
   Expected values are worked out here with Node's own Buffer and crypto, not with the program's code.
   Run: node encoder-decoder/test.js   (after node encoder-decoder/build.js) */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const H = require('../build/harness');
const { section, check } = H;
const APP = __dirname, PKG = fs.readdirSync(APP).find(f => f.endsWith('.portdapp'));
const DOCS = 'P:\\User\\Documents', CFG = 'P:\\User\\Config\\encoder-decoder';
const b64u = s => Buffer.from(s).toString('base64url');
const hashes = buf => Object.fromEntries([['SHA-1', 'sha1'], ['SHA-256', 'sha256'], ['SHA-384', 'sha384'], ['SHA-512', 'sha512'], ['MD5', 'md5']].map(([a, n]) => [a, crypto.createHash(n).update(buf).digest('hex')]));

(async () => {
  console.log('Encoder-Decoder tests\n  package  ' + PKG + '\n  portd    ' + path.relative(path.join(__dirname, '..'), H.PORTD) + '\n  browser  ' + (H.BROWSER || 'Playwright Chromium'));
  const ctx = await H.profile({ touch: true });
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write']);
  const page = await H.openPortD(ctx), P = H.on(page);
  const clip = () => page.evaluate(() => navigator.clipboard.readText());
  let f;
  const launch = async () => { await P.icon('Encoder-Decoder').dblclick(); await P.settle(600); f = await P.frame(); await f.waitForFunction(() => window.__ed && __ed.ready); };
  const val = sel => f.locator(sel).inputValue();
  const msg = id => f.locator('#p-' + id + ' .msg').first().innerText();
  const type = async (sel, t) => { await f.locator(sel).fill(''); await f.locator(sel).focus(); await page.keyboard.insertText(t); await P.settle(120); };
  const active = () => f.evaluate(() => document.activeElement && document.activeElement.id);
  const toast = () => f.locator('#toast').innerText();
  const opt = (id, v) => f.locator('#p-' + id + ' .sbtn[data-v="' + v + '"]');

  section('Installing');
  const d = await P.offerInstall(path.join(APP, PKG));
  check('the confirmation names Encoder-Decoder 1.0.0 and 7 files, and no file types', /Encoder-Decoder/.test(d) && /Version\s+1\.0\.0/.test(d) && /Files\s+7 files, /.test(d) && !/Can open/.test(d), d);
  await P.press('Install');
  check('installed, with a desktop shortcut', await P.ls('P:\\Programs\\encoder-decoder') === 'js|icon.svg|index.html|manifest.json|style.css' && await P.icon('Encoder-Decoder').count() === 1);
  await P.closeAll();
  await launch();
  check('it opens on Base64 with the cursor in the input', await f.locator('#t-b64').getAttribute('aria-selected') === 'true' && await active() === 'b64-in' && await P.titles() === 'Encoder-Decoder');

  section('Base64');
  const s1 = 'Grüße, world 😀 <tag> & more?';
  await page.keyboard.insertText(s1); await P.settle(150);
  check('typing gives UTF-8 Base64 straight away', await val('#b64-out') === Buffer.from(s1).toString('base64'));
  await page.keyboard.press('Alt+c'); await P.settle(150);
  check('Alt+C copies the result', await clip() === Buffer.from(s1).toString('base64') && /^Copied/.test(await toast()));
  await opt('b64', 'url').click(); await P.settle(100);
  check('Base64URL uses - and _ and no padding', await val('#b64-out') === Buffer.from(s1).toString('base64url'));
  await f.locator('#b64-in').focus(); await page.keyboard.press('Alt+s'); await P.settle(150);
  check('Alt+S swaps: the Base64URL becomes the input, the direction is Decode, and the text comes back', await val('#b64-in') === Buffer.from(s1).toString('base64url') && await val('#b64-out') === s1 && await opt('b64', 'dec').getAttribute('aria-pressed') === 'true');
  await type('#b64-in', 'aGVs bG8=\n'); check('spaces and line breaks are ignored when decoding', await val('#b64-out') === 'hello');
  await type('#b64-in', 'a+b/'); check('a standard Base64 character in Base64URL mode is explained', /"\+" at position 2 is not allowed\. That looks like standard Base64/.test(await msg('b64')) && await val('#b64-out') === '');
  await opt('b64', 'std').click(); await type('#b64-in', Buffer.from([0xff, 0xfe, 0x41]).toString('base64'));
  check('bytes that are not UTF-8 are shown one per byte, with a note and their hex', await val('#b64-out') === 'ÿþA' && /not UTF-8 text.*ff fe 41/.test(await msg('b64')));
  await f.locator('#p-b64 select').selectOption('latin1'); await opt('b64', 'enc').click(); await type('#b64-in', 'café');
  check('Latin-1 encodes one byte per character', await val('#b64-out') === Buffer.from('café', 'latin1').toString('base64'));
  await type('#b64-in', 'Ω'); check('…and says plainly when a character is not Latin-1', /"Ω" \(position 1\) is not a Latin-1 character/.test(await msg('b64')));
  await f.locator('#p-b64 select').selectOption('utf8');
  await f.locator('#p-b64 .chk').click(); await type('#b64-in', 'x'.repeat(100));
  check('Lines of 76 wraps the result', (await val('#b64-out')).split('\n').map(l => l.length).join() === '76,60');
  await f.locator('#p-b64 .chk').click();
  await f.locator('#p-b64 .btn', { hasText: /^Clear$/ }).click(); await P.settle(100);
  check('Clear empties the input', await val('#b64-in') === '' && await val('#b64-out') === '' && /Ctrl\+Z/.test(await toast()));
  await page.keyboard.press('Control+z'); await P.settle(100);
  check('Ctrl+Z brings it back', await val('#b64-in') === 'x'.repeat(100));

  section('URL, Hex and HTML');
  await page.keyboard.press('Alt+2'); await P.settle(100);
  check('Alt+2 opens URL with the cursor in its input', await active() === 'url-in');
  const u = 'name=Zoë & Ann/50%?';
  await page.keyboard.insertText(u); await P.settle(100);
  check('URL encode is encodeURIComponent', await val('#url-out') === encodeURIComponent(u));
  await f.locator('#p-url .chk', { hasText: 'Whole address' }).click(); await type('#url-in', 'https://example.test/a b?q=ü&x=1');
  check('Whole address keeps : / ? & =', await val('#url-out') === encodeURI('https://example.test/a b?q=ü&x=1'));
  await opt('url', 'dec').click(); await type('#url-in', 'a+b%20c%C3%A9');
  check('decoding turns + into a space (can be turned off)', await val('#url-out') === 'a b cé');
  await type('#url-in', '100%'); check('a broken % is explained', /not valid URL encoding/.test(await msg('url')));
  await page.keyboard.press('Alt+3'); await P.settle(100);
  await page.keyboard.insertText('Hi é');
  await P.settle(100);
  check('Hex shows the UTF-8 bytes, spaced, and counts them', await val('#hex-out') === '48 69 20 c3 a9' && /5 bytes/.test(await msg('hex')));
  await f.locator('#p-hex select').selectOption(':'); await f.locator('#p-hex .chk').click(); await P.settle(100);
  check('separator and upper case are options', await val('#hex-out') === '48:69:20:C3:A9');
  await opt('hex', 'dec').click(); await type('#hex-in', '0x48 0x69,c3a9');
  check('decoding accepts 0x, spaces and commas', await val('#hex-out') === 'Hié');
  await type('#hex-in', 'abc'); check('an odd number of digits is explained', /odd number of digits \(3\)/.test(await msg('hex')));
  await page.keyboard.press('Alt+4'); await P.settle(100);
  await page.keyboard.insertText('<a href="x">Tom & Jerry\'s café</a>'); await P.settle(100);
  check('HTML encode escapes & < > " \'', await val('#html-out') === '&lt;a href=&quot;x&quot;&gt;Tom &amp; Jerry&#39;s café&lt;/a&gt;');
  await f.locator('#p-html .chk').click(); await P.settle(100);
  check('…and can write non-ASCII as numbers', (await val('#html-out')).includes('caf&#233;'));
  await opt('html', 'dec').click(); await type('#html-in', '&lt;b&gt; &amp;amp; &#233; &#x1F600; &copy; &nosuch;');
  check('decoding handles named and numbered entities, and lists unknown ones', await val('#html-out') === '<b> &amp; é 😀 © &nosuch;' && /&nosuch;/.test(await msg('html')));

  section('JWT');
  await page.keyboard.press('Alt+5'); await P.settle(100);
  const now = Math.floor(Date.now() / 1000);
  const tok = (pl, hd) => b64u(JSON.stringify(hd || { alg: 'RS256', typ: 'JWT' })) + '.' + b64u(JSON.stringify(pl)) + '.c2lnbmF0dXJl';
  check('it says plainly that the signature is not checked', /Decoding only\. The signature is not checked/.test(await f.locator('#p-jwt .warnline').innerText()));
  await page.keyboard.insertText('Bearer ' + tok({ sub: 'alice', name: 'Ålice', iat: 1700000000, exp: 1700003600 })); await P.settle(150);
  let jo = await f.locator('#jwt-out').innerText();
  check('header and payload are shown as formatted JSON ("Bearer " is fine)', /"alg": "RS256"/.test(jo) && /"name": "Ålice"/.test(jo) && /"exp": 1700003600/.test(jo));
  check('an old token is marked expired, with exp and iat in local time and UTC', /Expired [\d,]+ days ago/.test(jo) && /Expires \(exp\)\s+14 Nov 2023, \d\d:\d\d:\d\d\s+2023-11-14 23:13:20 UTC/.test(jo) && /Issued \(iat\)/.test(jo) && await f.locator('.chip.bad', { hasText: 'Expired' }).count() === 1, jo);
  await type('#jwt-in', tok({ sub: 'bob', exp: now + 7200, nbf: now + 600 }));
  jo = await f.locator('#jwt-out').innerText();
  check('a current token says when it ends; a future nbf says it is not valid yet', /Not expired: ends in 1 hour/.test(jo) && /Not valid yet: starts in 9 minutes|Not valid yet: starts in 10 minutes/.test(jo), jo);
  await f.locator('#jwt-out .jblock', { hasText: 'Payload' }).locator('.btn').click(); await P.settle(100);
  check('Copy copies the payload JSON', JSON.parse(await clip()).sub === 'bob');
  await type('#jwt-in', 'a.b.c.d.e'); check('an encrypted token (5 parts) is explained', /encrypted \(JWE\)/.test(await f.locator('#jwt-out').innerText()));
  await type('#jwt-in', 'not a token'); check('something else is explained', /A JWT has 3 parts separated by dots; this has 1\./.test(await f.locator('#jwt-out').innerText()));
  await type('#jwt-in', tok({ sub: 'x' }, { alg: 'none' }).replace(/\.[^.]*$/, '.'));
  check('an unsigned token is marked "Not signed"', await f.locator('.chip.bad', { hasText: 'Not signed' }).count() === 1 && /No expiry/.test(await f.locator('#jwt-out').innerText()));

  section('Hash');
  await page.keyboard.press('Alt+6'); await P.settle(100);
  await page.keyboard.insertText('abc'); await P.settle(500);
  const hv = await f.evaluate(() => Object.fromEntries([...document.querySelectorAll('.hrow')].map(r => [r.dataset.alg, r.querySelector('.hval').textContent])));
  const want = hashes(Buffer.from('abc'));
  check('SHA-1, SHA-256, SHA-384, SHA-512 and MD5 of typed text are all right', JSON.stringify(hv) === JSON.stringify(want), hv);
  check('MD5 is labelled "not secure"', /not secure/.test(await f.locator('.hrow[data-alg=MD5]').innerText()));
  await f.locator('#hash-expect').fill('SHA256: ' + want['SHA-256'].toUpperCase()); await P.settle(100);
  check('Compare finds which hash matches, whatever the case or a label in front', /✓ Matches the SHA-256 hash/.test(await f.locator('#hash-verdict').innerText()) && await f.locator('.hrow.match').getAttribute('data-alg') === 'SHA-256');
  await f.locator('#hash-expect').fill('deadbeef'); await P.settle(100);
  check('…and says when nothing matches', /Does not match/.test(await f.locator('#hash-verdict').innerText()));
  await f.locator('.hrow[data-alg="SHA-256"] .btn').click(); await P.settle(100);
  check('each hash has its own Copy', await clip() === want['SHA-256']);
  await f.locator('#p-hash .chk').click(); await P.settle(100);
  check('Upper case is an option', await f.locator('.hrow[data-alg="SHA-1"] .hval').innerText() === want['SHA-1'].toUpperCase());
  await f.locator('#p-hash .chk').click();
  const bin = crypto.randomBytes(3000);
  await P.ev(async b64 => PortDHost.vfs.write('P:\\User\\Documents\\random.bin', 'data:application/octet-stream;base64,' + b64, 'dataurl'), bin.toString('base64'));
  await P.write(DOCS + '\\notes.txt', 'Line one\r\nZoë\r\n');
  await f.locator('#p-hash .btn', { hasText: 'Open file…' }).click(); await P.settle(300); await P.pickInDialog('random.bin'); await P.settle(600);
  const hb = await f.evaluate(() => Object.fromEntries([...document.querySelectorAll('.hrow')].map(r => [r.dataset.alg, r.querySelector('.hval').textContent])));
  check('a binary file is hashed byte for byte (all five right)', JSON.stringify(hb) === JSON.stringify(hashes(bin)) && /random\.bin/.test(await f.locator('.filebox').innerText()) && /3,000 bytes/.test(await f.locator('.filebox').innerText()));
  await f.locator('#p-hash .btn', { hasText: 'Open file…' }).click(); await P.settle(300); await P.pickInDialog('notes.txt'); await P.settle(600);
  const ht = await f.evaluate(() => document.querySelector('.hrow[data-alg="SHA-256"] .hval').textContent);
  check('a text file is hashed as its UTF-8 bytes, and that is said', ht === hashes(Buffer.from('Line one\r\nZoë\r\n'))['SHA-256'] && /hashed as UTF-8/.test(await f.locator('.filebox').innerText()));
  await f.locator('.filebox .btn').click(); await P.settle(400);
  check('Back to text hashes the typed text again', await f.evaluate(() => document.querySelector('.hrow[data-alg=MD5] .hval').textContent) === want.MD5);

  section('Generate');
  await page.keyboard.press('Alt+7'); await P.settle(100);
  check('Alt+7 opens Generate with Generate focused', await active() === 'genBtn');
  await f.locator('#p-gen input[type=number]').fill('5'); await P.settle(150);
  let g = (await val('#gen-out')).split('\n');
  check('5 GUIDs, each a random version 4 one', g.length === 5 && g.every(x => /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(x)), g);
  await f.locator('#p-gen .chk', { hasText: 'Upper case' }).click(); await f.locator('#p-gen .chk', { hasText: 'With { }' }).click(); await P.settle(100);
  check('upper case and braces are options', /^\{[0-9A-F]{8}-[0-9A-F]{4}-4[0-9A-F]{3}-[89AB][0-9A-F]{3}-[0-9A-F]{12}\}$/.test((await val('#gen-out')).split('\n')[0]));
  await f.locator('#p-gen input[type=number]').fill('1000'); await P.settle(300);
  g = (await val('#gen-out')).split('\n');
  check('1,000 at once, all different', g.length === 1000 && new Set(g).size === 1000);
  const first = await val('#gen-out'); await page.keyboard.press('Alt+g'); await P.settle(200);
  check('Alt+G makes new ones', await val('#gen-out') !== first);
  await opt('gen', 'password').click(); await f.locator('#p-gen input[type=number]').fill('24'); await P.settle(150);
  const pws = [];
  for (let i = 0; i < 40; i++) { await f.locator('#genBtn').click(); pws.push(await val('#gen-out')); }
  check('passwords: the length asked for, at least one of each kind, no look-alikes', pws.every(p => p.length === 24 && /[A-Z]/.test(p) && /[a-z]/.test(p) && /[0-9]/.test(p) && /[^A-Za-z0-9]/.test(p) && !/[Il1O0o]/.test(p)) && new Set(pws).size === 40, pws.slice(0, 3));
  check('strength is estimated in bits', /^About \d+ bits: very strong\.$/.test(await f.locator('#p-gen .msg').innerText()), await f.locator('#p-gen .msg').innerText());
  for (const k of ['A–Z', 'a–z', '0–9', 'Symbols']) await f.locator('#p-gen .chk', { hasText: new RegExp('^\\s*' + k + '$') }).click();
  await P.settle(100);
  check('with no kinds of character chosen it says so', /Choose at least one kind/.test(await f.locator('#p-gen .msg').innerText()));
  await f.locator('#p-gen .chk', { hasText: '0–9' }).click(); await f.locator('#p-gen input[type=number]').fill('4'); await P.settle(150);
  check('a short digits-only password is marked weak', /^\d{4}$/.test(await val('#gen-out')) && /weak/.test(await f.locator('#p-gen .msg').innerText()));
  await opt('gen', 'phrase').click(); await f.locator('#p-gen input[type=number]').fill('6'); await f.locator('#p-gen select').selectOption(' '); await P.settle(150);
  const words = await f.evaluate(() => Codec.WORDS);
  const ph = (await val('#gen-out')).split(' ');
  check('a passphrase of 6 capitalised words from the list, one with a digit', ph.length === 6 && ph.every(w => /^[A-Z][a-z]+\d?$/.test(w) && words.includes(w.replace(/\d$/, '').toLowerCase())) && ph.filter(w => /\d$/.test(w)).length === 1, ph);
  check('the list has hundreds of different words', words.length > 600 && new Set(words).size === words.length);
  await f.locator('#p-gen .btn', { hasText: /^Copy$/ }).click(); await P.settle(100);
  check('Copy copies it', await clip() === ph.join(' '), [await clip(), ph.join(' '), await val('#gen-out'), await toast()]);

  section('Keyboard, touch, theme, and what is kept');
  await f.locator('#t-gen').focus(); await page.keyboard.press('ArrowLeft'); await page.keyboard.press('ArrowLeft');
  check('arrow keys move along the tabs', await active() === 't-jwt' && !(await f.locator('#p-jwt').isHidden()));
  await f.locator('#t-hex').tap(); await opt('hex', 'enc').tap(); await P.settle(100);
  check('touch works on tabs and buttons', !(await f.locator('#p-hex').isHidden()) && await opt('hex', 'enc').getAttribute('aria-pressed') === 'true');
  await f.locator('#themeBtn').click(); await f.locator('#themeBtn').click(); await P.settle(150);
  check('the theme button goes to light, then dark', await f.evaluate(() => document.documentElement.dataset.theme) === 'dark' && await f.evaluate(() => getComputedStyle(document.body).backgroundColor) === 'rgb(26, 30, 38)');
  await P.settle(300);
  const saved = JSON.parse(await P.read(CFG + '\\settings.json'));
  check('settings.json keeps the tab, each tool\'s options and the theme', saved.tab === 'hex' && saved.theme === 'dark' && saved.opts.hex.sep === ':' && saved.opts.hex.upper === true && saved.opts.gen.kind === 'phrase' && saved.opts.gen.words === 6);
  check('…and nothing that was typed or made: no text, token or password anywhere in the data folder', await P.ls(CFG) === 'settings.json' && !/Grüße|alice|bob|abc"|Zoë/.test(JSON.stringify(saved)) && !JSON.stringify(saved).includes(ph[0]));
  await P.closeAll(); await H.reload(page); await launch();
  check('after a PortD reload: the same tab and options, dark, and empty boxes', await f.locator('#t-hex').getAttribute('aria-selected') === 'true' && await opt('hex', 'enc').getAttribute('aria-pressed') === 'true' && await f.locator('#p-hex select').inputValue() === ':' && await f.evaluate(() => document.documentElement.dataset.theme) === 'dark' && await val('#hex-in') === '' && await val('#b64-in') === '');
  await f.locator('#themeBtn').click();
  await P.closeAll();

  section('No errors');
  check('no console errors in PortD or in Encoder-Decoder', ctx.errors.length === 0, ctx.errors);
  await ctx.close();

  section('Outside PortD: the page opened straight from its folder');
  const c2 = await H.profile({ colorScheme: 'dark' });
  const sp = await H.openStandalone(c2, path.join(APP, 'src', 'index.html'));
  await sp.waitForFunction(() => window.__ed && __ed.ready, null, { timeout: 8000 });
  await sp.keyboard.insertText('abc'); await sp.keyboard.press('Alt+6'); await sp.keyboard.insertText('abc'); await sp.waitForTimeout(400);
  check('it runs, follows the system\'s dark theme, and hashes', await sp.inputValue('#b64-out') === 'YWJj' && await sp.evaluate(() => document.documentElement.dataset.theme === 'dark') && await sp.locator('.hrow[data-alg="SHA-256"] .hval').innerText() === want['SHA-256']);
  await sp.reload(); await sp.waitForFunction(() => window.__ed && __ed.ready);
  check('the open tab is kept in the browser\'s storage; the text is not', await sp.locator('#t-hash').getAttribute('aria-selected') === 'true' && await sp.inputValue('#hash-in') === '');
  check('no console errors outside PortD', c2.errors.length === 0, c2.errors);
  await c2.close();
  H.finish();
})().catch(e => { console.error('\nTEST CRASHED\n', e); process.exit(2); });
