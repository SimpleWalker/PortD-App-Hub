/* Regex Tester: tests in the real PortD 1.0.0, in headless Chrome, with real mouse, keyboard and touch input.
   Run: node regex-tester/test.js   (after node regex-tester/build.js) */
'use strict';
const fs = require('fs'), path = require('path');
const H = require('../build/harness');
const { section, check } = H;
const APP = __dirname, PKG = fs.readdirSync(APP).find(f => f.endsWith('.portdapp'));
const DOCS = 'P:\\User\\Documents', CFG = 'P:\\User\\Config\\regex-tester';

(async () => {
  console.log('Regex Tester tests\n  package  ' + PKG + '\n  portd    ' + path.relative(path.join(__dirname, '..'), H.PORTD) + '\n  browser  ' + (H.BROWSER || 'Playwright Chromium'));
  const ctx = await H.profile({ touch: true });
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write']);
  const page = await H.openPortD(ctx), P = H.on(page);
  const clip = () => page.evaluate(() => navigator.clipboard.readText());
  let f;
  const launch = async () => { await P.icon('Regex Tester').dblclick(); await P.settle(600); f = await P.frame(); await f.waitForFunction(() => window.__rx && __rx.ready); };
  const status = () => f.locator('#status').innerText();
  const count = () => f.evaluate(() => __rx.res ? __rx.res.count : null);
  const marks = () => f.evaluate(() => [...document.querySelectorAll('#hl mark')].map(m => m.textContent).join('|'));
  const toast = () => f.locator('#toast').innerText();
  const typePattern = async p => { await f.locator('#pattern').fill(''); await f.locator('#pattern').focus(); await page.keyboard.type(p); await P.settle(350); };
  const setText = async t => { await f.locator('#text').fill(t); await P.settle(350); };
  const active = () => f.evaluate(() => document.activeElement && document.activeElement.id);

  section('Installing');
  const d = await P.offerInstall(path.join(APP, PKG));
  check('the confirmation names Regex Tester 1.0.0, .txt and .log, and 6 files', /Regex Tester/.test(d) && /Version\s+1\.0\.0/.test(d) && /Can open\s+\.txt, \.log/.test(d) && /Files\s+6 files, /.test(d), d);
  await P.press('Install');
  check('installed, with a desktop shortcut, without taking over .txt from Notepad', await P.ls('P:\\Programs\\regex-tester') === 'js|icon.svg|index.html|manifest.json|style.css' && await P.icon('Regex Tester').count() === 1 && JSON.stringify(JSON.parse(await P.read('P:\\User\\Config\\associations.json')).assoc) === '{}');
  check('PortD offers .txt and .log in a notice, which can be dismissed', /^Regex Tester can open \.txt and \.log files/.test(await P.notices()), await P.notices());
  await page.locator('#notices .notice .btn', { hasText: /^Dismiss$/ }).click(); await P.settle(100);
  await P.closeAll();

  section('A first look');
  await launch();
  check('it starts with an example: named groups and dates, 3 matches highlighted', await count() === 3 && await marks() === '2026-11-02|2026-11-09|2026-11-16' && await status() === '3 matches.');
  check('the pattern box has the keyboard, and the window is titled Regex Tester', await active() === 'pattern' && await P.titles() === 'Regex Tester');
  check('each match lists its groups, named and numbered', /#1 at 15, length 10/.test(await f.locator('#m-0').innerText()) && /year \(\$1\): "2026"/.test(await f.locator('#m-0').innerText()) && /\$3: "02"/.test(await f.locator('#m-0').innerText()));
  const lay = await f.evaluate(() => { const ta = document.getElementById('text'), hl = document.getElementById('hl'), a = getComputedStyle(ta), b = getComputedStyle(hl); return [a.font === b.font, a.paddingLeft === b.paddingLeft, a.lineHeight === b.lineHeight, a.whiteSpace === b.whiteSpace]; });
  check('the highlight layer has exactly the text\'s font, padding, line height and wrapping', lay.every(Boolean), lay);

  section('Typing a pattern, flags and mistakes');
  await setText('Error at 10:15\nerror at 11:20\nWARN at 12:00\nERROR: disk full');
  await typePattern('^error');
  check('matches follow as you type (live): ^error finds nothing at the start of the text', await count() === 0 && /No match/.test(await status()));
  await f.locator('.flag[data-f=m]').click(); await P.settle(300);
  check('m: ^ matches at each line start, so "error" on line 2 matches', await count() === 1 && await marks() === 'error');
  await f.locator('.flag[data-f=i]').click(); await P.settle(300);
  check('i: ignoring case finds 3', await count() === 3 && await marks() === 'Error|error|ERROR' && await f.locator('#flagText').innerText() === 'gim');
  check('flag buttons say whether they are on', await f.locator('.flag[data-f=i]').getAttribute('aria-pressed') === 'true' && await f.locator('.flag[data-f=s]').getAttribute('aria-pressed') === 'false');
  await f.locator('.flag[data-f=g]').click(); await P.settle(300);
  check('without g only the first match is found, and it says how to find them all', await count() === 1 && /Turn on g/.test(await status()));
  await f.locator('.flag[data-f=g]').click(); await P.settle(200);
  await typePattern('(\\d+:');
  check('a mistake in the pattern gives a plain message and no crash', /^This pattern has a mistake: Unterminated group\.$/.test(await status()) && await count() === null && await f.evaluate(() => document.getElementById('pattern').classList.contains('bad')));
  await typePattern('(?<h>\\d\\d):(?<m>\\d\\d)');
  check('fixing it shows the matches again', await count() === 3 && await marks() === '10:15|11:20|12:00');
  await typePattern('\\b');
  check('empty matches (\\b) are counted and drawn as thin markers', await count() === 30 && await f.evaluate(() => document.querySelectorAll('#hl mark.z').length) === 30 && /\(empty match\)/.test(await f.locator('#m-0').innerText()));

  section('The Matches list');
  await typePattern('(?<h>\\d\\d):(?<m>\\d\\d)');
  await f.locator('#m-1').click(); await P.settle(150);
  check('clicking a match selects it in the text and marks it', await f.evaluate(() => { const t = document.getElementById('text'); return t.value.slice(t.selectionStart, t.selectionEnd); }) === '11:20' && await f.locator('#hl mark.cur').innerText() === '11:20' && await f.locator('#m-1').getAttribute('aria-selected') === 'true');
  await f.locator('#mList').focus(); await page.keyboard.press('ArrowDown'); await P.settle(100);
  check('Down moves to the next match', await f.evaluate(() => __rx.cur) === 2 && await f.locator('#hl mark.cur').innerText() === '12:00');
  await page.keyboard.press('Enter'); await P.settle(100);
  check('Enter puts the cursor on it in the text', await active() === 'text' && await f.evaluate(() => { const t = document.getElementById('text'); return t.value.slice(t.selectionStart, t.selectionEnd); }) === '12:00');

  section('Replace');
  await page.keyboard.press('Alt+2'); await P.settle(150);
  check('Alt+2 opens Replace', !(await f.locator('#p-replace').isHidden()) && await f.locator('#tab-replace').getAttribute('aria-selected') === 'true');
  await f.locator('#repl').fill('[$<m> past $1 ($&)]'); await P.settle(200);
  check('$<name>, $1 and $& work, live', (await f.locator('#rOut').innerText()).startsWith('Error at [15 past 10 (10:15)]\nerror at [20 past 11 (11:20)]') && /Every match replaced \(3\)/.test(await f.locator('#rInfo').innerText()));
  await f.locator('#repl').fill('$$$2'); await P.settle(150);
  check('$$ gives a dollar sign', (await f.locator('#rOut').innerText()).startsWith('Error at $15'));
  await f.locator('#copyBtn').click(); await P.settle(200);
  check('Copy result copies the whole result', (await clip()).split('\n').length === 4 && (await clip()).startsWith('Error at $15\nerror at $20') && /^Copied the result/.test(await toast()));

  section('Limits: many matches, a long run, risky patterns');
  await page.keyboard.press('Alt+1');
  await f.evaluate(() => { const t = document.getElementById('text'); t.value = 'ab '.repeat(5000); t.dispatchEvent(new Event('input')); });
  await typePattern('ab');
  check('5,000 matches are counted, the first 1,000 listed and highlighted', await count() === 5000 && await f.locator('#mList .mrow').count() === 1000 && await f.evaluate(() => document.querySelectorAll('#hl mark').length) === 1000 && /5,000 matches\. The first 1,000 are shown/.test(await status()));
  await f.evaluate(() => { const t = document.getElementById('text'); t.value = 'a'.repeat(4e6); t.dispatchEvent(new Event('input')); });
  await typePattern('a'); await P.settle(900);
  const st = await status();
  check('a run that takes too long stops at about half a second, says so, and keeps what it found', await f.evaluate(() => __rx.res && __rx.res.stopped) === 'time' && /^Stopped after 0\.\d s: [\d,]+ matches found so far\./.test(st), st);
  check('…and Live turns itself off, saying why', await f.evaluate(() => __rx.settings.live) === false && /Live is now off/.test(st) && await f.locator('#liveBtn').getAttribute('aria-pressed') === 'false');
  check('the replace result is not shown for a stopped run', /Not shown: matching was stopped/.test(await f.locator('#rInfo').innerText()));
  await setText('aaaaaaaaaaaa!');
  await typePattern('x');
  check('with Live off, nothing runs until Run', /Live is off/.test(await status()));
  await page.keyboard.press('Control+Enter'); await P.settle(200);
  check('Ctrl+Enter runs it', /No match/.test(await status()));
  await f.locator('#liveBtn').click(); await P.settle(200);
  check('the Live button turns it back on (and runs)', await f.evaluate(() => __rx.settings.live) === true && JSON.parse(await P.read(CFG + '\\settings.json')).live === true);
  await typePattern('(a+)+$');
  check('(a+)+$ is not run as you type, with a warning in plain words', await count() === null && /^Not run as you type: this pattern has a repeated group that holds another repeat/.test(await status()));
  await typePattern('(\\w|\\d)*!');
  check('(\\w|\\d)* is caught too (choices that can match the same text)', /repeated group of choices/.test(await status()));
  await typePattern('(a+)+$');
  await f.locator('#runBtn').click(); await P.settle(200);
  check('Run tries it anyway on purpose (short text: fine)', await count() === 0 && /No match/.test(await status()));

  section('Saved patterns');
  await setText('2026-11-21 and 1999-01-05');
  await typePattern('(?<y>\\d{4})-(\\d\\d)-(\\d\\d)');
  await page.keyboard.press('Alt+2'); await f.locator('#repl').fill('$3.$2.$<y>');
  await page.keyboard.press('Control+s'); await P.settle(150);
  check('Ctrl+S asks for a name, suggesting the pattern', !(await f.locator('#saveDlg').isHidden()) && await active() === 'saveName' && await f.locator('#saveName').inputValue() === '(?<y>\\d{4})-(\\d\\d)-(\\d\\d)');
  await f.locator('#saveName').fill('ISO date'); await page.keyboard.press('Enter'); await P.settle(200);
  const sv = JSON.parse(await P.read(CFG + '\\saved.json'));
  check('it is saved with its flags, replacement and text', sv.v === 1 && sv.patterns[0].name === 'ISO date' && sv.patterns[0].flags === 'gim' && sv.patterns[0].replacement === '$3.$2.$<y>' && sv.patterns[0].text === '2026-11-21 and 1999-01-05' && /^Saved "ISO date"/.test(await toast()));
  await f.locator('#saveBtn').click(); await f.locator('#saveName').fill('iso DATE'); await f.locator('#saveOk').click(); await P.settle(100);
  check('saving under a name that exists asks first', /already called "ISO date"/.test(await f.locator('#saveWarn').innerText()) && await f.locator('#saveOk').innerText() === 'Replace it' && !(await f.locator('#saveDlg').isHidden()));
  await page.keyboard.press('Escape'); await P.settle(100);
  check('Esc closes it, nothing changed, focus back on the button', await f.locator('#saveDlg').isHidden() && JSON.parse(await P.read(CFG + '\\saved.json')).patterns.length === 1 && await active() === 'saveBtn');
  await typePattern('zzz'); await setText('something else');
  await page.keyboard.press('Alt+p'); await P.settle(150);
  check('Alt+P lists saved patterns, with Load focused', /ISO date/.test(await f.locator('#savedList').innerText()) && await f.evaluate(() => document.activeElement.textContent) === 'Load');
  await page.keyboard.press('Enter'); await P.settle(400);
  check('Load brings back the pattern, flags, replacement and text, and runs it', await f.locator('#pattern').inputValue() === '(?<y>\\d{4})-(\\d\\d)-(\\d\\d)' && await f.evaluate(() => __rx.flags) === 'gim' && await f.locator('#text').inputValue() === '2026-11-21 and 1999-01-05' && await count() === 2);
  await f.locator('#text').focus(); await page.keyboard.press('Control+z'); await P.settle(300);
  check('Ctrl+Z in the text brings back the text from before Load', await f.locator('#text').inputValue() === 'something else');
  await f.locator('#savedBtn').click(); await P.settle(100);
  await f.locator('#savedList .btn.danger').click(); await P.settle(100);
  check('Delete asks for a second click', await f.locator('#savedList .btn.danger').innerText() === 'Click again to delete' && JSON.parse(await P.read(CFG + '\\saved.json')).patterns.length === 1);
  await f.locator('#savedList .btn.danger').click(); await P.settle(200);
  check('a second click deletes it', JSON.parse(await P.read(CFG + '\\saved.json')).patterns.length === 0 && /Nothing saved yet/.test(await f.locator('#savedList').innerText()));
  await page.keyboard.press('Escape');

  section('Opening text and log files');
  await P.write(DOCS + '\\server.log', '[INFO] start\n[ERROR] disk full\n[WARN] slow\n[ERROR] retry failed\n');
  await setText('typed by hand');
  await page.keyboard.press('Control+o'); await P.settle(300);
  await P.pickInDialog('server.log'); await P.settle(500);
  check('Ctrl+O opens PortD\'s Open dialog; the log becomes the test text', await f.locator('#text').inputValue() === '[INFO] start\n[ERROR] disk full\n[WARN] slow\n[ERROR] retry failed\n' && /^Opened server\.log/.test(await toast()) && /server\.log - Regex Tester/.test(await P.titles()));
  await typePattern('\\[(ERROR|WARN)\\]');
  check('…and the pattern runs on it', await count() === 3);
  await f.locator('#text').focus(); await page.keyboard.press('Control+z'); await P.settle(300);
  check('Ctrl+Z brings back the text from before', await f.locator('#text').inputValue() === 'typed by hand');
  await f.evaluate(() => __rx.writeSession());
  await P.rowMenu(DOCS, 'server.log'); await P.mi('Open with').hover(); await P.settle(250);
  check('Open with lists Regex Tester for .log', (await P.menuItems(1)).split('|').includes('Regex Tester'), await P.menuItems(1));
  await P.mi('Regex Tester', 1).click(); await P.settle(800);
  const f2 = await P.frame(); await f2.waitForFunction(() => window.__rx && __rx.ready);
  check('opening a file starts a second window with that file', await page.locator('.win iframe[title*="Regex Tester"]').count() === 2 && (await f2.locator('#text').inputValue()).startsWith('[INFO] start'));
  await P.closeAll();

  section('Coming back later, theme and keys');
  await H.reload(page); await launch();
  check('after a PortD reload the last session is back: pattern, flags, text and tab', await f.locator('#pattern').inputValue() === '\\[(ERROR|WARN)\\]' && await f.evaluate(() => __rx.flags) === 'gim' && (await f.locator('#text').inputValue()).startsWith('[INFO] start') && await count() === 3, [await f.locator('#pattern').inputValue(), await f.evaluate(() => __rx.flags), (await f.locator('#text').inputValue()).slice(0, 20), await count()]);
  await page.keyboard.press('F1'); await P.settle(100);
  check('F1 shows the cheat sheet', !(await f.locator('#p-cheat').isHidden()) && /\(\?<name>abc\)/.test(await f.locator('#p-cheat').innerText()) && await active() === 'tab-cheat');
  await page.keyboard.press('ArrowLeft'); await P.settle(100);
  check('arrow keys move along the tabs', !(await f.locator('#p-replace').isHidden()) && await active() === 'tab-replace');
  await f.locator('#tab-matches').tap(); await P.settle(100);
  await f.locator('.flag[data-f=i]').tap(); await P.settle(300);
  check('touch works on tabs and flags', !(await f.locator('#p-matches').isHidden()) && await count() === 3 && await f.evaluate(() => __rx.flags) === 'gm');
  await f.locator('#themeBtn').click(); await f.locator('#themeBtn').click(); await P.settle(150);
  check('the theme button goes to light, then dark, and is saved', await f.evaluate(() => document.documentElement.dataset.theme) === 'dark' && JSON.parse(await P.read(CFG + '\\settings.json')).theme === 'dark');
  check('dark colours: dark page, light text', await f.evaluate(() => getComputedStyle(document.body).backgroundColor) === 'rgb(26, 30, 38)' && await f.evaluate(() => getComputedStyle(document.getElementById('text')).color) === 'rgb(230, 233, 239)');
  await f.locator('#themeBtn').click();
  await typePattern('(a+)+$'); await f.evaluate(() => __rx.writeSession()); await P.settle(100);
  await P.closeAll(); await launch();
  check('a risky pattern from last time is not run on start, so it can\'t lock PortD again', /^Not run as you type/.test(await status()) && await count() === null);
  await P.closeAll();

  section('No errors');
  check('no console errors in PortD or in Regex Tester', ctx.errors.length === 0, ctx.errors);
  await ctx.close();

  section('Outside PortD: the page opened straight from its folder');
  const c2 = await H.profile({ colorScheme: 'dark' });
  const sp = await H.openStandalone(c2, path.join(APP, 'src', 'index.html'));
  await sp.waitForFunction(() => window.__rx && __rx.ready, null, { timeout: 8000 });
  check('it runs the example and follows the system\'s dark theme', await sp.evaluate(() => __rx.res.count === 3 && document.documentElement.dataset.theme === 'dark'));
  await sp.fill('#pattern', 'kept'); await sp.waitForTimeout(800);
  await sp.reload(); await sp.waitForFunction(() => window.__rx && __rx.ready);
  check('the session is kept in the browser\'s storage', await sp.inputValue('#pattern') === 'kept' && await sp.evaluate(() => !!localStorage.getItem('portd-hub:regex-tester:session.json')));
  check('no console errors outside PortD', c2.errors.length === 0, c2.errors);
  await c2.close();
  H.finish();
})().catch(e => { console.error('\nTEST CRASHED\n', e); process.exit(2); });
